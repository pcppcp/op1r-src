#!/usr/bin/env python3
"""Writes reactor_sin.h: REACTOR's loop sine, -lrint(32767 sin(2 pi i / 2048)) for i = 0..2047, so no table is built
at note on. Negative on purpose: the Mac model read the firmware table the way fmbell's sine() does, which gives
-sin, and the rods' and the loop's signs shape the sound (with +sin the rods' sidebands are far weaker).

    python3 synth_sdk/plugins/reactor/gen_tables.py

Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math
from pathlib import Path

N = 2048
vals = [-int(round(32767 * math.sin(2 * math.pi * i / N))) for i in range(N)]
rows = [', '.join(f'{v:6d}' for v in vals[i:i + 12]) for i in range(0, N, 12)]
Path(__file__).with_name('reactor_sin.h').write_text(
    '/* Generated by gen_tables.py: -lrint(32767 sin(2 pi i / 2048)). Copyright (C) 2026 Hundekraft. GPL-3.0-or-later\n'
    ' * with the OP-1 firmware permission (see LICENSE and NOTICE). */\n'
    '#ifndef REACTOR_SIN_H\n#define REACTOR_SIN_H\n#include <stdint.h>\n'
    f'static const int16_t rx_sin[{N}] = {{\n' + ',\n'.join('    ' + r for r in rows) + '\n};\n#endif\n')
