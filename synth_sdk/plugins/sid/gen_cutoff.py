#!/usr/bin/env python3
"""Generates sid_cutoff_log[] in sid_filter_tables.h: the white knob's cutoff coefficients (65 points, log law).

The design is the 8580 table's cutoff range as it sounds at 44.1 kHz: coefficient g = 2 sin(pi fc / fs) from
round(6 * (3385 / 6)^(i / 64)) / 4096 (10 Hz .. 6.0 kHz). R246 runs a voice at 88.2 kHz (OP1_VOICE_RATE), so the same
cutoff in Hz is g' = 2 sin(pi fc / 88200) = 2 sin(asin(g / 2) / 2). The filter keeps 14 extra fractional bits (Q26, was Q24
at 44.1 kHz): the halved coefficients keep the smoothing's 1 % resolution at the dark end, and the largest value (28.4
million) keeps |high| <= 170496 times (c >> 12) <= 6926 inside 32 bits, as before.

    python3 gen_cutoff.py            print the block
    python3 gen_cutoff.py --write    replace it in sid_filter_tables.h
Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math
import re
import sys
from pathlib import Path

Q = 26                       # fractional bits of the coefficient in the filter
FS_DESIGN, FS_UNIT = 44100.0, 88200.0


def table():
    out = []
    for i in range(65):
        g = 6 * (3385 / 6) ** (i / 64) / 4096                  # coefficient at the design rate
        fc = FS_DESIGN / math.pi * math.asin(g / 2)             # its cutoff in Hz
        out.append(round(2 * math.sin(math.pi * fc / FS_UNIT) * 2 ** Q))
    return out


def block():
    t = table()
    rows = [' ' + ','.join(str(v) for v in t[i:i + 8]) + ',' for i in range(0, 64, 8)] + [' ' + str(t[64])]
    return ('/* Kennel\'s continuous white control: logarithmic coefficients over the same 6..3385 (Q12, 44.1 kHz)\n'
            ' * endpoints as the 8580 table, i.e. 10 Hz .. 6.0 kHz, as g = 2 sin(pi fc / 88200) in Q26 (R246 runs a voice at\n'
            ' * 88.2 kHz). 64 spans, linearly interpolated; generated by gen_cutoff.py.\n'
            ' * This is a knob response law, not a new claim about the physical SID DAC. */\n'
            'static const int32_t sid_cutoff_log[65] = {\n' + '\n'.join(rows) + '\n};\n')


if __name__ == '__main__':
    path = Path(__file__).with_name('sid_filter_tables.h')
    if '--write' in sys.argv:
        s = path.read_text()
        a = s.index("/* Kennel's continuous white control")
        b = s.index('};', a) + 3
        path.write_text(s[:a] + block() + s[b:])
    else:
        print(block(), end='')
