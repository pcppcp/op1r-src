#!/usr/bin/env python3
"""Writes eva_tables.h: a sine and the choir's three vowels; nothing is built in the audio callback.

  ev_sin     1025 points of a sine, Q15 (LFOs, the Quindar tones)
  ev_hz      F1, F2 per vowel (oo, ah, ee), Hz: a choir's vowels, softened (ee's F2 lowered, oo's F1 raised a little)
             so they colour the pad instead of speaking
  ev_bw      their bandwidths, Hz: wide, so the bands blend with the lowpass
  ev_level   their levels, Q15
  ev_recip_hz exact floor(2^24/hz) for the vowel frequency range
  ev_lp2x    a one-pole coefficient k (Q15) made for 22.05 kHz -> the same pole at 44.1 kHz, 1 - sqrt(1 - k), for
             k = i * 512 (eva.c lp2x interpolates): the pad's and the radio's lowpass curves keep their Hz (2026-11-03:
             R246's voice call is 128 samples at 88.2 kHz, so EVA's 64 internal samples are 44.1 kHz, not 22.05)
Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math, os


def table(name, values, ctype="int16_t"):
    out = [f"static const {ctype} {name}[{len(values)}] = {{"]
    out += ["    " + ", ".join(str(x) for x in values[i:i + 16]) + "," for i in range(0, len(values), 16)]
    return out + ["};", ""]


sine = [round(32767 * math.sin(2 * math.pi * i / 1024)) for i in range(1025)]
# eva.c's sinq reads the first quarter (257 entries) and folds it: the quarters must mirror exactly
assert all(sine[n] == (-1 if (n >> 8) & 2 else 1) * sine[256 - (n & 255) if (n >> 8) & 1 else n & 255] for n in range(1025))
# oo, ah, ee: (F1, F2), (bandwidths), (levels in dB)
VOWELS = [
    ((380, 800), (160, 220), (0, -4)),
    ((720, 1150), (180, 240), (0, -1)),
    ((330, 1900), (150, 300), (0, 0)),
]
hz, bw, lv = [], [], []
for f, b, a in VOWELS:
    hz += list(f)
    bw += list(b)
    lv += [round(32767 * 10 ** (x / 20)) for x in a]

out = ["/* generated by gen_tables.py */", "#include <stdint.h>", "#define EV_VOWELS 3", ""]
out += table("ev_sin", sine)
out += ["/* vowels oo, ah, ee: two formants each */"]
out += table("ev_hz", hz) + table("ev_bw", bw) + table("ev_level", lv)
out += ["/* Reciprocal seed; vowel_ratio corrects its quotient to exact floor division. */", f"#define EV_VOWEL_HZ_MIN {min(hz)}", f"#define EV_VOWEL_HZ_MAX {max(hz)}", f"#define EV_VOWEL_BW_MAX {max(bw)}"]
out += table("ev_recip_hz", [(1 << 24) // f for f in range(min(hz), max(hz) + 1)], "uint16_t")
out += ["/* a 22.05 kHz one-pole coefficient -> 44.1 kHz: 1 - sqrt(1 - i / 64), Q15 (eva.c lp2x) */"]
out += table("ev_lp2x", [min(32767, round(32768 * (1 - math.sqrt(1 - i / 64)))) for i in range(65)], "uint16_t")
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "eva_tables.h"), "w").write("\n".join(out))
