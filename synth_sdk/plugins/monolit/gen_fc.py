#!/usr/bin/env python3
"""Write monolit_fc.S: MONOLIT's ladder loops, Moai's zero-delay filter chunks (moai/gen_fc.py, imported, not copied) for
the two paths MONOLIT uses, without resonance (k = 0) and with it, renamed mo_fc_plain / mo_fc_res and run over 64
samples a call instead of 32 (two calls a block: half the coefficient solves and call overheads of Moai's four), and
over 128 (one call: the block, while the cutoff holds). The
input is the oscillators' int32 mix (at half scale, within 16 bits), read from the pointer passed as Moai's fb
argument (no separate pack pass); the output goes to b.
Bit for bit monolit.c's mo_chunk_c (kern_check.py compares them on bcore).

    python3 gen_fc.py            (writes monolit_fc.S next to this file)

Copyright (C) 2026 Hundekraft. Derived from moai.c, Copyright (C) 2026 moai contributors.
GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import importlib.util
from pathlib import Path

HERE = Path(__file__).resolve().parent
spec = importlib.util.spec_from_file_location('moai_gen_fc', HERE.parent / 'moai' / 'gen_fc.py')
G = importlib.util.module_from_spec(spec)
spec.loader.exec_module(G)

CHUNK = 64                                    # = MO_CHUNK in monolit.c
# (name, fb, res, sat, tr, samples): the 128-sample pair runs a whole block in one call while the cutoff holds
VARIANTS = [('mo_fc_plain', 0, 0, 0, 0, CHUNK), ('mo_fc_res', 0, 1, 0, 0, CHUNK),
            ('mo_fc_plain128', 0, 0, 0, 0, 128), ('mo_fc_res128', 0, 1, 0, 0, 128)]
FB_ARG = 36 + 16 + 16                         # [SP + FB_ARG] in the prologue: the fb argument, here the mix pointer

_body = G.body


def body(fb, res, sat, tr):
    """Moai's operations, but the input is the int32 mix (mo_osc's sums, at half scale: within 16 bits): a 32-bit load
    of the word instead of Moai's 16-bit load of b[n]; only its low half is read, as mo_chunk_c's b[n]"""
    ops = _body(fb, res, sat, tr)
    i = next(j for j, o in enumerate(ops) if o.stream == 'IN')
    ops[i].text = 'R0 = [I0++]'
    return ops


G.body = body


def main():
    lines = ['/* monolit_fc.S: MONOLIT\'s ladder, Moai\'s zero-delay filter chunk (moai.c filter_chunk_t without feedback,',
             f' * saturation or transistor stages) over {CHUNK} samples, in Blackfin assembly, bit for bit monolit.c\'s mo_chunk_c.',
             ' * Generated by gen_fc.py from moai/gen_fc.py (edit those, not this file). Arguments: R0 = b, R1 = lad,',
             ' * R2 = lc, [SP + 12] = gxog, [SP + 16] = the int32 mix (Moai\'s fb word: fb is 0 here; its low halves are the input),',
             ' * [SP + 20] = st (mu at +12), [SP + 24] = pyp, [SP + 28] = pdc.',
             ' * Copyright (C) 2026 Hundekraft. Derived from moai.c, Copyright (C) 2026 moai contributors.',
             ' * GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */',
             '#ifdef __bfin__                 /* the host builds (golden.py, the tests) use the C */', '']
    for v in VARIANTS:
        out, n = G.variant(*v[:5])
        assert out.count('\tP1 = 32;') == 1
        out = [l.replace('\tP1 = 32;', f'\tP1 = {v[5]};') for l in out]
        assert out.count('\tI0 = R0;') == 1                        # the input: the fb argument's word (fb is 0 here)
        out[out.index('\tI0 = R0;')] = f'\tR3 = [SP + {FB_ARG}];\n\tI0 = R3;'
        lines += out
        print(f'{v[0]:12} {n} packets a sample')
    lines += ['#endif', '']
    (HERE / 'monolit_fc.S').write_text('\n'.join(lines))


if __name__ == '__main__':
    main()
