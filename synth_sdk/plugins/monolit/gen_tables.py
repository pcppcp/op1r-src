"""Writes monolit_tables.h: the ladder's one-pole coefficient per 1/8 octave of cutoff (Q15, g = 1 - exp(-2 pi f / fs),
f = 40 Hz * 2^(x / 4096) for x = 0 .. 9 octaves), capped where the unit-delay feedback stays stable at full heat."""
import math, os

FS, F0, STEP, OCT = 44100.0, 40.0, 512, 9
G_MAX = 21000                                   # ~0.64: about 7 kHz; above it the cutoff stops rising

g = []
for i in range(OCT * 4096 // STEP + 2):         # one extra entry so x = max can interpolate
    f = F0 * 2 ** (i * STEP / 4096)
    g.append(min(G_MAX, round((1 - math.exp(-2 * math.pi * f / FS)) * 32768)))

out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'monolit_tables.h')
with open(out, 'w') as fh:
    fh.write('/* Generated by gen_tables.py: edit that, not this.\n'
             ' * Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */\n')
    fh.write(f'#define BR_G_STEP {STEP}\n#define BR_X_MAX {OCT * 4096 - 1}\n')
    fh.write(f'static const int16_t br_g[{len(g)}] = {{\n')
    for i in range(0, len(g), 12):
        fh.write(' ' + ','.join(str(v) for v in g[i:i + 12]) + ',\n')
    fh.write('};\n')
print(out)
