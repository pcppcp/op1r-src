"""Writes monolit_tables.h, the tables of MONOLIT's zero-delay ladder (Moai's, 2026-11-04; PROVENANCE.md):
  MO_G[i]     the stage coefficient gg = t / (1 + t), t = tan(theta), Q15, for a cutoff of 20 Hz * 2^(i/16), i = 0 .. 160
              (10 octaves); theta = pi f / fs up to 8 kHz, then on to the design's top (atan(4) at 44.1 kHz) so the filter
              opens fully at the top. MONOLIT's cutoff x (Q12 octaves over 40 Hz) is the position (x >> 2) + 1024 (Q10
              octaves over 20 Hz), 64 per entry.
  MO_GG_K0/K1/KA/KB  where lad_coef takes the resonance out at the top (gg 18022 .. 26214 at 44.1 kHz, as gg at fs)
  MO_INV[i]   1 / (1 + i/16), Q15: the feedback solve without a division
FS: the voice's real rate, 88.2 kHz (R246 renders 128 samples a call at 88.2 kHz)."""
import math, os

FS, FS_DESIGN = 88200.0, 44100.0
F0, STEPS_PER_OCT, F_MAX, F_KNEE = 20.0, 16, 20480.0, 8000.0
THETA_TOP = math.atan(4.0)


def theta(f):
    if f <= F_KNEE:
        return math.pi * f / FS
    x = (f - F_KNEE) / (F_MAX - F_KNEE)
    t0 = math.pi * F_KNEE / FS_DESIGN
    return (t0 + (THETA_TOP - t0) * x) * FS_DESIGN / FS


def gg_at_fs(g44):
    return math.tan(math.atan(g44 / (32768 - g44)) * FS_DESIGN / FS)


def g44_of(g):
    t = math.tan(math.atan(g / (32768 - g)) * FS / FS_DESIGN)
    return t / (1 + t) * 32768


n = int(round(math.log2(F_MAX / F0) * STEPS_PER_OCT))
g_tab = []
for i in range(n + 2):
    t = math.tan(theta(F0 * 2 ** (i / STEPS_PER_OCT)))
    g_tab.append(min(32767, round(t / (1 + t) * 32768)))
kk = [round(t / (1 + t) * 32768) for t in (gg_at_fs(18022), gg_at_fs(26214))]
pts = [(kk[1] - g, max(0.0, (26214 - g44_of(g)) * 4 - 1)) for g in range(kk[0], kk[1] + 1)]
s11 = sum(d * d for d, _ in pts); s12 = sum(d ** 3 for d, _ in pts); s22 = sum(d ** 4 for d, _ in pts)
t1 = sum(d * f for d, f in pts); t2 = sum(d * d * f for d, f in pts)
det = s11 * s22 - s12 * s12
KA, KB = round((t1 * s22 - t2 * s12) / det * 256), round((s11 * t2 - s12 * t1) / det * 256 * 65536)
inv_tab = [min(32767, round(32768 / (1 + i / 16))) for i in range(16 * 5 + 2)]


def arr(name, vals, per=12):
    rows = [','.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const uint16_t {name}[{len(vals)}] = {{\n ' + ',\n '.join(rows) + ',\n};\n'


out = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'monolit_tables.h')
with open(out, 'w') as fh:
    fh.write('/* Generated by gen_tables.py: edit that, not this.\n'
             ' * Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).\n'
             ' * The ladder tables follow Moai\'s (Copyright (C) 2026 moai contributors, same licence). */\n')
    fh.write(f'#define MO_G_N {n}\n#define MO_X_MAX 36863\n#define MO_GG_K0 {kk[0]}\n#define MO_GG_K1 {kk[1]}\n'
             f'#define MO_GG_KA {KA}\n#define MO_GG_KB {KB}\n')
    fh.write(arr('MO_G', g_tab))
    fh.write(arr('MO_INV', inv_tab))
print(out)
