static unsigned char scratch[3][OP1_FX_SCRATCH_BYTES + 32];
static void *op1_fx_scratch(int p) { return scratch[p] + 4; }    /* misaligned on purpose: rackverb.c aligns it */
static int32_t op1_fx_param_q15(const int16_t *p, int i) { return p[i] < 0 ? 0 : p[i]; }
#include "rackverb.c"

static int16_t word_for(int step, int n) { return (int16_t)(((2 * step + 1) * 32768) / (2 * n)); }

static int check(void)
{
    int fails = 0;
    uint32_t rng = 5;
    for (int u = 0; u < U_N; u++) {
        int16_t params[8] = { 9000, 31760, 16384, 0, 0, 32767, word_for(0, 2), word_for(u, 4) };
        FX_rackverb.mono.init(2);
        for (int pr = 0; pr < U_COUNT[u]; pr++) {
            params[3] = word_for(pr, RV_PROG_STEPS);
            int dry_calls = 0, peak = 0;
            for (int call = 0; call < 700; call++) {            /* ~1 s each */
                int16_t l[64], r[64], a[64], b[64];
                for (int i = 0; i < 64; i++) {
                    rng = rng * 1664525u + 1013904223u;
                    int16_t v = call < 200 ? (int16_t)((int32_t)rng >> 18) : 0;   /* noise burst, -6 dBFS */
                    l[i] = a[i] = v; r[i] = b[i] = (int16_t)-v;
                }
                FX_rackverb.render_stereo(2, l, r, params);
                if (!memcmp(l, a, sizeof l) && !memcmp(r, b, sizeof r) && call < 200) dry_calls++;
                for (int i = 0; i < 64; i++) { int x = abs(l[i]); if (x > peak) peak = x; }
            }
            if (rv_live[2][0] != u || rv_live[2][1] != pr + U_FIRST[u]) { printf("FAIL %d %d live %d %d\n", u, pr, rv_live[2][0], rv_live[2][1]); fails++; }
            if (dry_calls > 40) { printf("FAIL %d %d: %d dry calls\n", u, pr, dry_calls); fails++; }
            if (peak >= 32767 && 0) fails++;
            printf("unit %d prog %02d %-22s dry calls %2d peak %5d\n", u, pr + U_FIRST[u], rv_name(u, pr), dry_calls, peak);
        }
    }
    /* MIX 0 is exactly dry once running */
    int16_t params[8] = { 20000, 20000, 0, word_for(13, RV_PROG_STEPS), 0, 32767, word_for(0, 2), word_for(0, 4) };
    FX_rackverb.mono.init(0);
    for (int call = 0; call < 200; call++) {
        int16_t l[64], a[64];
        for (int i = 0; i < 64; i++) { rng = rng * 1664525u + 1013904223u; l[i] = a[i] = (int16_t)(rng >> 16); }
        FX_rackverb.mono.render(0, l, params);
        if (memcmp(l, a, sizeof l)) { printf("FAIL mix 0 not dry (call %d)\n", call); fails++; break; }
    }
    printf("%d fail\n", fails);
    return fails != 0;
}

/* FEEDBACK at the top on every program: a noise burst, then silence must fall below -60 dBFS within 20 s (no
 * runaway); prints each shape's worst tail so the ceilings (FB_CEIL) can be set from evidence */
/* the tail after a noise burst with FEEDBACK at gain g (Q15, direct): seconds until below -60 dBFS, 99 if never */
static double tail_at(int u, int pr, int32_t g)
{
#ifdef RV_FBCEIL_SEARCH
    rv_fb_override = g;
#else
    (void)g;
#endif
    uint32_t rng = 9;
    int16_t params[8] = { 32767, 31763, 32767, word_for(pr, RV_PROG_STEPS), 0, 32767, word_for(0, 2), word_for(u, 4) };
    FX_rackverb.mono.init(2);
    int last = 0, calls = 16 * 689 + 200;
    for (int call = 0; call < calls; call++) {
        int16_t l[64], r[64];
        for (int i = 0; i < 64; i++) {
            rng = rng * 1664525u + 1013904223u;
            l[i] = r[i] = (call >= 30 && call < 170) ? (int16_t)((int32_t)rng >> 18) : 0;
        }
        FX_rackverb.render_stereo(2, l, r, params);
        for (int i = 0; i < 64; i++) if (abs(l[i]) > 32 || abs(r[i]) > 32) { last = call; break; }
    }
    return last >= calls - 10 ? 99 : (last - 170) / 689.0;
}
/* every program's FEEDBACK ceiling: the largest gain whose tail still ends within 12 s, less 15 %: rv_fbceil.h */
static int fbceil(const char *out)
{
#ifdef RV_FBCEIL_SEARCH
    FILE *f = fopen(out, "w");
    fprintf(f, "/* Generated by rackverb_host fbceil (built with -DRV_FBCEIL_SEARCH): do not edit. FEEDBACK's ceiling per\n"
               " * program (Q15 gain on the wet sum fed back): the largest gain whose tail after a noise burst still falls below\n"
               " * -60 dBFS within 12 s, less 15 %%. Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware\n"
               " * permission (see LICENSE and NOTICE). */\n#ifndef RV_FBCEIL_H\n#define RV_FBCEIL_H\n#include <stdint.h>\n"
               "static const uint16_t rv_fbceil[4][100] = {\n");
    for (int u = 0; u < U_N; u++) {
        fprintf(f, "    {");
        for (int pr = 0; pr < 100; pr++) {
            int32_t lo = 0, hi = 32767;
            if (pr < U_COUNT[u]) {
                if (tail_at(u, pr, hi) <= 12) lo = hi;
                else for (int it = 0; it < 9; it++) { int32_t m = (lo + hi) >> 1; if (tail_at(u, pr, m) <= 12) lo = m; else hi = m; }
            }
            fprintf(f, "%s%s%d", pr ? "," : " ", pr % 16 == 15 ? "\n     " : "", (int)(lo * 85 / 100));
        }
        fprintf(f, " },\n");
    }
    fprintf(f, "};\n#endif\n");
    fclose(f);
    return 0;
#else
    (void)out; fprintf(stderr, "build with -DRV_FBCEIL_SEARCH\n"); return 2;
#endif
}

static int fbcheck(int16_t fbword)
{
    int fails = 0;
    uint32_t rng = 9;
    for (int u = 0; u < U_N; u++)
        for (int pr = 0; pr < U_COUNT[u]; pr++) {
            int16_t params[8] = { fbword, 31763, 32767, word_for(pr, RV_PROG_STEPS), 0, 32767, word_for(0, 2), word_for(u, 4) };
            FX_rackverb.mono.init(2);
            int last_loud = 0, calls = 20 * 689 + 400;
            for (int call = 0; call < calls; call++) {
                int16_t l[64], r[64];
                for (int i = 0; i < 64; i++) {
                    rng = rng * 1664525u + 1013904223u;
                    l[i] = r[i] = (call >= 30 && call < 170) ? (int16_t)((int32_t)rng >> 18) : 0;
                }
                FX_rackverb.render_stereo(2, l, r, params);
                for (int i = 0; i < 64; i++) if (abs(l[i]) > 32) { last_loud = call; break; }
            }
            double t = (last_loud - 170) / 689.0;
            int bad = last_loud >= calls - 10;
            if (bad || t > 8) printf("unit %d prog %02d %-22s tail %.1f s%s\n", u, pr + U_FIRST[u], rv_name(u, pr), t, bad ? " RUNAWAY" : "");
            fails += bad;
        }
    printf("feedback %d: %d runaway\n", fbword, fails);
    return fails != 0;
}

/* every knob (and the page-2 words) swept every call, as cost_check's "knob sweep": no crash, bounded */
static int sweep(void)
{
    uint32_t rng = 3;
    int16_t params[8] = { 0 };
    for (int p = 0; p < 3; p++) FX_rackverb.mono.init(p);
    for (int call = 0; call < 20000; call++) {
        for (int k = 0; k < 8; k++) params[k] = (int16_t)((call * (97 + 31 * k)) & 32767);
        if (call % 3000 > 2000) { rng = rng * 1664525u + 1013904223u; params[rng % 8] = (int16_t)(rng >> 17); }
        int16_t l[64], r[64];
        for (int i = 0; i < 64; i++) { rng = rng * 1664525u + 1013904223u; l[i] = r[i] = (int16_t)((int32_t)rng >> 17); }
        int pos = call % 3;
        if (pos == 2) FX_rackverb.render_stereo(2, l, r, params); else FX_rackverb.mono.render(pos, l, params);
    }
    printf("sweep ok\n");
    return 0;
}

static int render_file(char **v)
{
    int unit = atoi(v[0]), prog = atoi(v[1]), mode = atoi(v[2]);
    int16_t params[8] = { (int16_t)atoi(v[3]), (int16_t)atoi(v[4]), (int16_t)atoi(v[5]), word_for(prog - U_FIRST[unit], RV_PROG_STEPS),
                          0, (int16_t)atoi(v[6]), word_for(mode, 2), word_for(unit, 4) };
    FILE *fi = fopen(v[7], "rb");
    if (!fi) { perror(v[7]); return 1; }
    fseek(fi, 0, SEEK_END);
    long n = ftell(fi) / 4;
    fseek(fi, 0, SEEK_SET);
    float *in = malloc(n * 4), *out = malloc(n * 8);
    if (fread(in, 4, n, fi) != (size_t)n) return 1;
    fclose(fi);
    FX_rackverb.mono.init(2);
    int16_t z[64] = { 0 }, zr[64] = { 0 };
    for (int c = 0; c < 80; c++) FX_rackverb.render_stereo(2, z, zr, params);   /* clear and build first */
    for (long i = 0; i + 64 <= n; i += 64) {
        int16_t l[64], r[64];
        for (int k = 0; k < 64; k++) { float x = in[i + k] * 32767.f; l[k] = r[k] = (int16_t)(x > 32767 ? 32767 : (x < -32767 ? -32767 : x)); }
        FX_rackverb.render_stereo(2, l, r, params);
        for (int k = 0; k < 64; k++) { out[2 * (i + k)] = l[k] / 32768.f; out[2 * (i + k) + 1] = r[k] / 32768.f; }
    }
    FILE *fo = fopen(v[8], "wb");
    fwrite(out, 8, n / 64 * 64, fo);
    fclose(fo);
    return 0;
}

int main(int argc, char **argv)
{
    if (argc >= 2 && !strcmp(argv[1], "check")) return check();
    if (argc >= 2 && !strcmp(argv[1], "sweep")) return sweep();
    if (argc >= 3 && !strcmp(argv[1], "fbceil")) return fbceil(argv[2]);
    if (argc >= 2 && !strcmp(argv[1], "fbcheck")) return fbcheck(argc >= 3 ? (int16_t)atoi(argv[2]) : 32767);
    if (argc >= 11 && !strcmp(argv[1], "render")) return render_file(argv + 2);
    if (argc >= 4 && !strcmp(argv[1], "name")) { int u = atoi(argv[2]) & 3; printf("%s\n", rv_name(u, atoi(argv[3]) - U_FIRST[u])); return 0; }
    fprintf(stderr, "usage: rackverb_host check | render UNIT PROG MODE FB CUT MIX SIZE in.f32 out.f32\n");
    return 2;
}
