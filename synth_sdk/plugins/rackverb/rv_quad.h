/* rackverb unit 4, QUAD: a late-80s multi-effect in the style of a 16-bit rack quad processor (our own design).
 * Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
 *
 * Mono in, stereo out, 100 % wet, at QD_RATE = the FX call's 44,100 Hz, every stage at the full rate.
 * Five fixed configurations (qd_config):
 *   1  EQ (low shelf, mid peak, high shelf) > PITCH > DELAY > REVERB   presets  0..29
 *   2  LESLIE (horn Doppler + AM, drum AM) > DELAY > REVERB             presets 30..41
 *   3  GRAPHIC EQ (peaks at 64, 250, 1k, 4k, 12k) > DELAY               presets 42..53
 *   4  5-BAND EQ (shelves + 3 peaks) > PITCH > DELAY                   presets 54..65
 *   5  EQ (low shelf, mid peak, high shelf) > REVERB                   presets 66..89
 * PITCH: CHORUS, FLANGE (feedback), DETUNE (two crossfaded ramp taps per side: L up, R down), PHASER (6 first-order
 * allpasses, L = dry + wet, R = dry - wet). DELAY: MONO, STEREO (own L/R times), PING-PONG; feedback through a
 * one-pole lowpass. REVERB: PLATE, ROOM, CHAMBER, HALL (a Dattorro figure-eight tank, room and chamber with early
 * taps), REVERSE (a rising multi-tap cluster on a diffused line); each with an optional gate (hold, release).
 * Output mixer: out = dir * pre + dlev * delay taps + rlev * reverb, where pre is the signal after EQ / PITCH or
 * LESLIE; the reverb hears pre + dlev * delay taps (mono).
 */
#ifndef RV_QUAD_H
#define RV_QUAD_H
#include <stdint.h>

#define QD_RATE 44100            /* the FX call's rate */
#define QD_N 64                  /* samples per call */
#define QD_PRESETS 90
#define QD_STATE_MAX (212 * 1024) /* in the position's fast lease (op1_fx_fast) or big buffer (op1_fx_big), 32-byte aligned */

/* rings (int16), each a multiple of QD_N long and only as long as the presets need (gen_quad_presets.py checks) */
#define QD_RV_LEN  31808         /* reverb pool: one ring per tank element, or the reverse line (721 ms) */
#define QD_DLY_LEN 30912         /* each delay channel (701 ms: the longest delay, 700 ms) */
#define QD_PRE_LEN 6720          /* reverb pre-delay and early taps (152 ms) */
#define QD_PIT_LEN 2048          /* pitch / leslie line (46 ms; a power of two) */

/* block types in a preset row */
enum { QD_P_NONE, QD_P_CHORUS, QD_P_FLANGE, QD_P_DETUNE, QD_P_PHASER, QD_P_LESLIE };
enum { QD_D_NONE, QD_D_MONO, QD_D_STEREO, QD_D_PING };
enum { QD_R_NONE, QD_R_PLATE, QD_R_ROOM, QD_R_CHAMBER, QD_R_HALL, QD_R_REVERSE };
#define QD_RV_ELEMS 12           /* reverb ring regions: 4 input allpasses, then the tank (see rv_quad.c) */

/* one preset (rv_quad_presets.h, generated by gen_quad_presets.py). Q15 unless noted; times in samples at QD_RATE
   at SIZE 100 %. */
typedef struct {
 uint8_t cfg, neq, ptype, dtype, rtype, gate;
 int16_t eq[5][5];               /* b0 b1 b2 a1 a2, Q13 (RBJ cookbook, quantized and checked by the generator) */
 uint32_t prate, prate2;         /* LFO phase increments per sample (2^32 = a cycle); leslie: horn, drum; detune: ramp */
 int32_t pcen, pdep;             /* modulated delay centre and depth, Q8 samples (detune: base delay Q8, window in samples) */
 int16_t pfb, pdry, pwet;        /* flange feedback / phaser feedback; dry and wet levels */
 uint16_t pspread;               /* right LFO phase offset, Q16 of a turn */
 int16_t pa0, pa1;               /* phaser allpass coefficient range; leslie: horn AM, drum AM */
 int16_t px;                     /* leslie crossover one-pole coefficient */
 uint16_t dtl, dtr;              /* delay times */
 int16_t dfb, dfbr, ddamp, dlev; /* feedback L, R; loop lowpass coefficient (32767 = open); delay output level */
 int16_t rsize, rdec, rdamp, rbw;/* tank length scale; decay gain; damping and input bandwidth (one-pole coefs) */
 int16_t rdif1, rdif2, rddif1, rddif2;   /* input diffusion 1, 2; decay diffusion 1, 2 */
 int16_t rmod, rer, rlev, dir;   /* tank modulation depth (Q8 samples); early level; reverb and direct levels */
 uint16_t rpre, rert, rrev;      /* pre-delay; early pattern span; reverse cluster length */
 uint16_t rmrate;                /* tank LFO phase increment per sample, >> 8 */
 int16_t gthr, grel;             /* gate threshold (input peak); release multiplier per block */
 uint16_t ghold;                 /* gate hold, blocks */
} qd_preset;

/* ---- the kernels (rv_quad.c's qk_*_c references, rv_quad_kern.S on the Blackfin): QD_N samples each unless noted.
   Argument blocks: every field 4 bytes, at the byte offsets given (rv_quad_kern.S reads them by offset).
   The gains that go through mz() (aplerp's and damp's dec, dlyw's fb) are >= 0: the kernels take mz's bias from
   the other factor's sign. */
typedef struct { const int16_t *base; int32_t d, sd; int16_t *out; } qk_tap_t;                   /* 0 4 8 12 */
typedef struct { int16_t *o; const int16_t *b; uint32_t q, inc; } qk_xf_t;                       /* 0 4 8 12 */
typedef struct { int16_t *p, *x; int32_t m, g; } qk_aps_t;                                       /* 0 4 8 12; m samples */
typedef struct { const int16_t *p; int32_t f; const int16_t *x, *fb; int32_t dec; int16_t *v, *y; int32_t g; } qk_apl_t; /* 0..28 */
typedef struct { const int16_t *p; int32_t f; int16_t *u; int32_t z, dk, dec; } qk_dmp_t;        /* 0..20 */
typedef struct { int16_t *w; const int16_t *x, *v; int32_t z, k, fb; } qk_dw_t;                 /* 0..20 */
typedef struct { int32_t *a; const int16_t *v; int32_t g, sh; } qk_mac_t;                        /* 0 4 8 12 */
typedef struct { int16_t *o; const int32_t *a; int32_t sc, sh, g, gs, lev; } qk_ro_t;           /* 0..24 */
typedef struct { const int16_t *p[8]; int32_t g[4]; int32_t *a; int32_t sh, add; } qk_sum_t;   /* p 0..28, g 32..44 (two
                                                        gains a word, k even in the low half), a 48, sh 52, add 56 */
typedef struct { int16_t *w; const int16_t *al, *ar, *yl, *yr; int32_t dl; } qk_in_t;          /* 0..20 */
typedef struct { const int16_t *q; int16_t *x; int32_t z, k; } qk_bw_t;                         /* 0..12 */
typedef struct { int16_t *r; uint32_t len, h; } qd_ring_t;   /* a reverb ring: base, length, head */

/* per-call work area: every row-sized buffer and kernel argument block of the qd_render chain, written before read in
   each call (nothing carries over), so it can sit anywhere: the L1 pool's partition (rackverb.c claims it every call:
   one cycle a word, no cache misses, no SDRAM writes), else its SDRAM home. Not on the stack: the FX render can run on
   R246's 1,520-byte L1 kernel stack. Uses that never overlap in time share memory: the tank's wrap copies (w, written
   back by wend inside each half) and the output taps' spans (tb, read after both halves; the reverse cluster has no
   halves). 32-byte aligned (its rows start on lines). */
typedef struct {
 int16_t al[QD_N], ar[QD_N];     /* pre: after EQ and PITCH / LESLIE */
 int16_t yl[QD_N], yr[QD_N];     /* delay taps (LESLIE: its drum band first) */
 int16_t ql[QD_N];               /* the dry input for the pitch block's mix */
 int16_t tmp[QD_N + 32];         /* span copies across a ring's end */
 int16_t x[QD_N], fa[QD_N], fb[QD_N], u[QD_N];   /* tank input, cross feedback, damped line */
 int16_t m[QD_N], b[QD_N];       /* delay mono input; detune's second tap */
 union {
  int16_t w[4][QD_N];            /* the tank halves' wrap copies */
  int16_t tb[7][QD_N];           /* the reverb's tap spans: 7 a side (Dattorro), 4 (early, reverse) */
 } t;
 int32_t al32[QD_N], ar32[QD_N]; /* the reverb's tap sums */
 int32_t q[QD_RV_ELEMS];         /* tank delays (Q8) */
 qd_ring_t g[QD_RV_ELEMS];
 qk_sum_t sum;
 qk_apl_t apl;
 qk_dmp_t dmp;
 qk_ro_t ro;
 qk_tap_t tap;
 qk_xf_t xf;
 qk_dw_t dw;
 qk_aps_t aps;
 qk_in_t in;
 qk_bw_t bw;
} __attribute__((aligned(32))) qd_work;

typedef struct qd_state qd_state;
struct qd_state {              /* place it on a 32-byte boundary (rv_quad.c asserts the ring offsets) */
 /* rings first: they start on 32-byte lines when the state does (every ring length is a multiple of 16) */
 int16_t rv[QD_RV_LEN];
 int16_t dl[QD_DLY_LEN], dr[QD_DLY_LEN];
 int16_t pre[QD_PRE_LEN];
 int16_t pit[2 * QD_PIT_LEN];      /* stored twice (h and h + QD_PIT_LEN): reads need no mask */
 const qd_preset *p;
 int32_t eqs[5][5];              /* biquad x1 x2 y1 y2 and the carried truncation error */
 uint32_t ph[3];                 /* LFO phases: pitch / horn, drum, tank */
 uint32_t ramp[2];               /* detune ramps, L (up) and R (down) */
 int32_t aps[6][2];              /* phaser allpass x1, y1 */
 int32_t pfbv, xlp;              /* flange / phaser feedback sample; leslie crossover */
 int32_t dlp[2];                 /* delay loop lowpass */
 int32_t rbwz, rdz[2];           /* tank input bandwidth, damping */
 uint16_t rh[QD_RV_ELEMS];       /* reverb ring heads */
 int32_t sz, szp;                /* smoothed SIZE, Q15 0.5 .. 1.0 (16384 .. 32767), now and at the previous call; -1 = snap */
 int32_t gg, gprev;              /* gate gain, Q15, now and at the previous block */
 int32_t ghold;                  /* gate hold count, blocks */
 uint32_t hp, hd, hpre;          /* heads: pitch, delay, pre-delay */
 qd_work home;                   /* qd_render's work area (qd_render_w takes one of the caller's) */
};
_Static_assert(sizeof(qd_state) <= QD_STATE_MAX, "qd_state too large");
_Static_assert(QD_STATE_MAX + 31 <= 0x38000, "QUAD's state fits the core's fast lease (kn_mem.h KN_FX_FAST_SIZE)");

void qk_biquad(int32_t *st, const int16_t *c, int16_t *x);
void qk_lerp(const int16_t *p, int16_t *out, int32_t f);
void qk_tap(const qk_tap_t *t);
void qk_xfade(const qk_xf_t *t);
void qk_apslot(const qk_aps_t *t);
void qk_aplerp(const qk_apl_t *t);
int32_t qk_damp(const qk_dmp_t *t);
int32_t qk_dlyw(const qk_dw_t *t);
void qk_acc(int32_t *a, const int16_t *v, int32_t neg);
void qk_mac(const qk_mac_t *t);
void qk_gadd(int16_t *o, const int16_t *x, int32_t g);
int32_t qk_rvout(const qk_ro_t *t);
void qk_sum4(const qk_sum_t *t);
void qk_sum7(const qk_sum_t *t);
void qk_pmix(int16_t *o, const int16_t *x, int32_t wet_dry);
int32_t qk_rvin(const qk_in_t *t);
int32_t qk_bw(const qk_bw_t *t);

void qd_select(qd_state *s, int preset);
void qd_render(qd_state *s, const int16_t *in, int16_t *outl, int16_t *outr, int32_t size_q15);   /* on s->home */
/* the same with the caller's work area (rackverb.c: the L1 pool's partition, or its home); never kept across calls */
void qd_render_w(qd_state *s, qd_work *wk, const int16_t *in, int16_t *outl, int16_t *outr, int32_t size_q15);
const char *qd_name(int preset);
int qd_config(int preset);
#endif
