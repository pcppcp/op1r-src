import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
FS = 44100


def lp_biquads(fc):
    """2-pole Butterworth low-pass, one RBJ biquad, Q14: (b0, b1, b2, -a1, -a2)"""
    out = []
    for q in (0.7071,):
        w = 2 * math.pi * fc / FS
        c, s = math.cos(w), math.sin(w)
        al = s / (2 * q)
        a0 = 1 + al
        b = [(1 - c) / 2 / a0, (1 - c) / a0, (1 - c) / 2 / a0]
        a = [-2 * c / a0, (1 - al) / a0]
        out.append([round(x * 16384) for x in (b[0], b[1], b[2], -a[0], -a[1])])
    return out


def main():
    RATES = (23437.5, 31250, 44100)                     # VERB I / FEX, VERB II, QUAD: CUTOFF runs at the unit's rate
    cut = [[min(32767, round(32767 * (1 - math.exp(-2 * math.pi * (500 * 22 ** (i / 32)) / fs)))) for i in range(33)] for fs in RATES]
    mixd = [round(32767 * math.cos(i / 32 * math.pi / 2)) for i in range(33)]
    mixw = [round(32767 * math.sin(i / 32 * math.pi / 2)) for i in range(33)]
    filt = {'AUTH': lp_biquads(10000), 'CLEAN1': lp_biquads(11000), 'CLEAN2': lp_biquads(14000)}
    L = lambda xs: ', '.join(str(x) for x in xs)
    rows = []
    for name, bq in filt.items():
        rows.append('    { %s },   /* %s */' % (L(bq[0]), name))
    h = f'''/* Generated by gen_tables.py: do not edit.
 * Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */
#ifndef RV_TABLES_H
#define RV_TABLES_H
#include <stdint.h>
/* CUTOFF one-pole coefficient (Q15) at 500 Hz * 22^(i/32), i = 0..32 (500 Hz .. 11 kHz), at the unit's rate:
 * 23,437.5 Hz (VERB I, FEX), 31,250 Hz (VERB II), 44,100 Hz (QUAD) */
static const int16_t rv_cut[3][33] = {{ {{ {L(cut[0])} }}, {{ {L(cut[1])} }}, {{ {L(cut[2])} }} }};
/* equal-power MIX, Q15: dry cos, wet sin */
static const int16_t rv_mixd[33] = {{ {L(mixd)} }};
static const int16_t rv_mixw[33] = {{ {L(mixw)} }};
/* the converters' analog low-pass at 44.1 kHz, one biquad (b0, b1, b2, -a1, -a2), Q14: AUTH 10 kHz, CLEAN 11 kHz
 * (VERB I, FEX), CLEAN 14 kHz (VERB II); 2-pole Butterworth */
static const int16_t rv_aa[3][5] = {{
{chr(10).join(rows)}
}};
#endif
'''
    (HERE / 'rv_tables.h').write_text(h)


if __name__ == '__main__':
    main()
