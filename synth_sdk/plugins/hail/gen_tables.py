#!/usr/bin/env python3
"""Generate hail_tables.h: the fixed-point tables of the HAIL FX (hail.c).

  bd_exp2[257]      2^(i/256) - 1, Q16: pow2 for pitch, grain size and grain rate
  bd_rand_ratio[256] Beads' random grain interval: -1 / LogOneMinusX(0.1 + 0.9 u), u = (i + 0.5) / 256, Q12
                     (trigger_generator.cc, LogOneMinusX is its 4-term series, not the real log)
  bd_inv_sqrt[34]   0.75 / sqrt(n), Q15: grain gain for n grains playing (0.75 = the mono line's centre pan gain)
  bd_recip[322]     2^30 / (i * 4096) for the limiters' gain (max / peak, peak in Q15), i = peak >> 12

    python3 synth_sdk/plugins/hail/gen_tables.py

Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE).
"""
import math
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def emit(name, ctype, vals, per=12):
    rows = [', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per)]
    return f'static const {ctype} {name}[{len(vals)}] = {{\n    ' + ',\n    '.join(rows) + '\n};\n'


def log_one_minus_x(x):
    return -x * (1.0 + x * (0.5 + x * (0.3333 + x * 0.25)))


exp2 = [round((2 ** (i / 256) - 1) * 65536) for i in range(257)]
rnd = [round(-1.0 / log_one_minus_x(0.1 + 0.9 * (i + 0.5) / 256) * 4096) for i in range(256)]
isq = [32767] + [round(0.75 / math.sqrt(n) * 32768) for n in range(1, 34)]
rec = [0x7FFFFFFF] + [round(2 ** 30 / (i * 4096)) for i in range(1, 322)]

out = ['/* generated by gen_tables.py: do not edit */', '#ifndef HAIL_TABLES_H', '#define HAIL_TABLES_H', '#include <stdint.h>',
       emit('bd_exp2', 'uint32_t', exp2, 8), emit('bd_rand_ratio', 'uint16_t', rnd), emit('bd_inv_sqrt', 'int16_t', isq),
       emit('bd_recip', 'uint32_t', rec, 8), '#endif', '']
open(os.path.join(HERE, 'hail_tables.h'), 'w').write('\n'.join(out))
