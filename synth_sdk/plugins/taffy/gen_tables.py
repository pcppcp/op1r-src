"""Writes taffy_tables.h: a cosine table of 1024 + 1 int16 points (Q15) for the taffy engine, and taffy_pairs.h: the
same points as (next - this) << 16 | this words for taffy_dsp.S (one load per interpolated read)."""
import math, os
N = 1024
HERE = os.path.dirname(os.path.abspath(__file__))
HEAD = "/* Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */"
v = [round(32767 * math.cos(2 * math.pi * i / N)) for i in range(N + 1)]
out = [HEAD, "/* generated by gen_tables.py */", "#include <stdint.h>", f"#define TF_SIZE {N}",
       "static const int16_t tf_cos[TF_SIZE + 1] = {"]
out += ["    " + ", ".join(str(x) for x in v[i:i + 16]) + "," for i in range(0, N + 1, 16)]
out += ["};", ""]
open(os.path.join(HERE, "taffy_tables.h"), "w").write("\n".join(out))
w = [((v[i + 1] - v[i]) & 0xFFFF) << 16 | (v[i] & 0xFFFF) for i in range(N)]
out = [HEAD, "/* generated by gen_tables.py: tf_pairs[i] = (tf_cos[i + 1] - tf_cos[i]) << 16 | tf_cos[i], for taffy_dsp.S */",
       "#include <stdint.h>", "static const uint32_t tf_pairs[1024] __attribute__((aligned(4))) = {"]
out += ["    " + ", ".join(f"0x{x:08x}" for x in w[i:i + 8]) + "," for i in range(0, N, 8)]
out += ["};", "/* tf_fade[i - 1] = 256 i << 16 | (32768 - 256 i), the knob crossfade's weights for i = 1..127, for taffy_dsp.S */",
        "static const uint32_t tf_fade[128] __attribute__((aligned(4))) = {"]
f = [(256 * i) << 16 | (32768 - 256 * i) for i in range(1, 128)] + [0]
out += ["    " + ", ".join(f"0x{x:08x}" for x in f[i:i + 8]) + "," for i in range(0, 128, 8)]
out += ["};", ""]
open(os.path.join(HERE, "taffy_pairs.h"), "w").write("\n".join(out))
