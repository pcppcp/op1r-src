def scene(face=True):
    out=['<svg xmlns="http://www.w3.org/2000/svg" width="320" height="160" viewBox="0 0 320 160">']
    # Fixed room: measured back-wall corners (104,61),(202,61),(202,119),(104,119).
    for i in range(15):
        t=i/14;out.append(shape([(8+304*t,8),(104+98*t,61)],GRID,.8))
        out.append(shape([(104+98*t,119),(15+290*t,156)],GRID,.8))
    for t in [0,.23,.42,.58,.72,.83,.92,1]:
        out.append(shape([(8+96*t,8+53*t),(312-110*t,8+53*t)],GRID,.8))
        out.append(shape([(104-89*t,119+37*t),(202+103*t,119+37*t)],GRID,.8))
    for x in range(104,203,10):out.append(shape([(x,61),(x,119)],GRID,.65))
    for y in range(61,120,10):out.append(shape([(104,y),(202,y)],GRID,.65))
    # the small person is green and moves with Gate at runtime.
    out.append('<g id="gate_person">')
    out.append(shape(ellipse(104,77,4.5,6),GREEN,1,True,'#010101'))
    out.append(shape([(100,84),(95,88),(94,103),(97,103),(97,91),(98,118),(103,118),(104,101),(105,118),(110,118),(110,91),(111,103),(114,103),(113,88),(108,84)],GREEN,1,True,'#010101'))
    out.append('</g>')
    out.append(shape([(15,84),(58,84),(58,119),(15,119)],WHITE,.8,True,'#010101'))
    out.append(shape([(18,87),(55,87),(55,116),(18,116)],WHITE,.65,True))
    out.append(shape([(23,100),(49,100),(51,108),(21,108)],WHITE,.7,True))
    for x in [27,45]:out.append(shape(ellipse(x,104,3,3),WHITE,.7,True))
    out.append(shape([(23,112),(49,112)],WHITE,.7))
    for x in range(22,52,4):out.append(shape([(x,89),(x+1.6,89)],WHITE,.7))
    for x in [20,26,47,53]:out.append(shape(ellipse(x,116,1,1),WHITE,.65,True))
    out.append(shape(ellipse(36,113,1.1,1.1),WHITE,.65,True))
    out.append(shape([(18,120),(22,124),(29,124),(32,121),(39,122),(43,126),(50,125),(56,127)],WHITE,.7))
    out.append(shape([(18,122),(20,127),(26,128),(31,124),(37,125),(42,129),(49,127),(56,128)],WHITE,.7))
    if face:
        out.append('<g id="face">')
        out.append(shape(ellipse(156,76,22,34),FACE,1,True))
        for lens in face_paths()[3:5]:out.append(shape(lens,'#010101',.2,True,'#010101'))
        for p in face_paths()[1:]:out.append(shape(p,FACE,1))
        out.append('</g>')
    out.append('</svg>');return '\n'.join(out)+'\n'

def main():
    (HERE/'father.svg').write_text(scene())
    out=['/* Original video-derived scene; generated by gen_svg.py. No firmware data. */',
         '#ifndef FATHER_GEOM_H','#define FATHER_GEOM_H','typedef struct {int32_t x,y;} father_xy;']
    paths=face_paths()
    for i,p in enumerate(paths):out.append(f'static const father_xy father_path_{i}[]={{'+','.join('{%d,%d}'%(round(x*256),round(y*256)) for x,y in p)+'};')
    out+=['typedef struct {const father_xy *p;unsigned count;} father_path;',
          'static const father_path father_paths[]={'+','.join('{father_path_%d,%d}'%(i,len(p)) for i,p in enumerate(paths))+'};','#endif']
    (HERE/'father_geom.h').write_text('\n'.join(out)+'\n')
if __name__=='__main__':main()
