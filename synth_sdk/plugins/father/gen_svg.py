#!/usr/bin/env python3
"""Video-measured Father scene, not extracted firmware art.

Reference: user's m2-res_1080p.mp4 (30 fps), frames 2/3/4 seconds. Approximate
filmed display bounds (620,66)..(1255,370) map to 320x160. Camera perspective,
compression and illumination limit precision. Distance49/80/99 footprint ratios
1/.63/.40 are observed; lower values extrapolate and clip at the viewport.
The layout raises the scene twelve pixels; runtime green-person gate feedback and bust COLOR shading
are new control feedback, not motion measured from the reference. No font/TE bytes.
"""
from pathlib import Path
import sys,math
HERE=Path(__file__).resolve().parent
sys.path.insert(0,str(HERE.parents[1]/'display'))
from svgart import shape as original_shape,ellipse,cubic

def shape(points,*args,**kwargs):
    return original_shape([(x,y-12) for x,y in points],*args,**kwargs)
GRID='#28595f'; FACE='#62a9c4'; GREEN='#00ef94'; WHITE='#aeb1c2'

def face_paths():
    paths=[]
    # All coordinates describe observed distance49; anchor156,94 remains fixed.
    paths.append(ellipse(156,76,22,34))
    paths.append([(134,66)]+cubic((134,66),(139,56),(173,56),(178,66)))
    paths.append([(134,68),(178,68)])
    paths.append([(134,69),(136,79),(141,82),(149,82),(153,79),(153,70),(136,70)])
    paths.append([(159,70),(159,79),(163,82),(173,82),(177,79),(178,69),(159,70)])
    paths.append([(153,72),(159,72)])
    paths.append([(140,74),(144,74)])
    paths.append([(164,74),(168,74)])
    paths.append([(130,70),(135,70)])
    paths.append([(177,70),(182,70)])
    paths.append([(134,74),(130,75),(130,83),(135,87)])
    paths.append([(178,74),(182,75),(182,83),(177,87)])
    paths.append([(145,106),(145,116),(139,119),(110,123),(99,130),(95,140),(95,150)])
    paths.append([(167,106),(167,116),(173,119),(202,123),(213,130),(217,140),(217,150)])
