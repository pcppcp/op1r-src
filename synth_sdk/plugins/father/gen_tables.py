"""Generate Father's ring geometry (father_lines.h) and per-line feedback gains (father_tables.h); no firmware inputs.

The design runs inside at 22,050 Hz (MW_IN = 32 samples per 64-sample FX call at 44,100 Hz: the input is decimated 2:1
and the wet output interpolated back) and the tank at 11,025 Hz (MW_N = 16 per call). Each line is a ring of exactly its longest modulated delay, so a
callback reads the samples it then overwrites (docs/father-redesign.md). Gains: g = 10^(-3 * delay / (11025 * RT60)),
RT60 = .35 + 7.65 * (index / 128)^2 seconds: the same decay per second as the 22,050 Hz design (lengths halved)."""
from pathlib import Path
import math
P = Path(__file__).resolve().parent
N = 16                                                    # tank samples per callback (11,025 Hz on the unit)
DELAYS = (317, 443, 577, 719, 929, 1063, 1327, 1583)     # ~ the 22,050 Hz design's 641..3163, halved, primes
DEPTH = [(1024 + i * 73) // 2 for i in range(8)]          # modulation depth, 1/256 sample
SPEED = [(17000 + i * 2473) * 2 for i in range(8)]        # triangle phase step per tank sample
ALLPASS = (113, 271, 167, 359)                            # left 1, left 2, right 1, right 2 (11,025 Hz)
EARLY = ((149, 263, 421, 631), (173, 307, 487, 733))      # early taps per output channel (22,050 Hz)
PRE_MAX = 662                                             # predelay at distance 99, 22,050 Hz samples
up16 = lambda x: (x + 15) & ~15                           # each ring starts on a 32-byte line
lens, offs, o = [], [], 0
for d, dp in zip(DELAYS, DEPTH):
    m = -(-dp // 256); L = d + m + 2; L += L & 1          # longest read (delay + depth + interpolation) fits
    assert d - m > N + 1
    lens.append(L); offs.append(o); o = up16(o + L)
tank_words = o
ap_offs, o = [], 0
for a in ALLPASS: ap_offs.append(o); o = up16(o + a)
ap_words = o
pre_len = up16(PRE_MAX + max(max(e) for e in EARLY) + 64 + 2)
arr = lambda xs: '{' + ','.join(map(str, xs)) + '}'
HDR = '/* Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission. */\n/* Generated by gen_tables.py. */\n'
(P / 'father_lines.h').write_text(HDR + f"""#ifndef FATHER_LINES_H
#define FATHER_LINES_H
#define MW_N {N}
#define MW_TANK_WORDS {tank_words}
#define MW_AP_WORDS {ap_words}
#define MW_PRE_LEN {pre_len}
#define MW_PRE_MAX {PRE_MAX}
""" + ''.join(f'#define MW_LEN{i} {L}\n#define MW_OFF{i} {offs[i]}\n' for i, L in enumerate(lens))
    + ''.join(f'#define MW_AP_LEN{i} {a}\n#define MW_AP_OFF{i} {ap_offs[i]}\n' for i, a in enumerate(ALLPASS)) + '#endif\n')
rows = []
for index in range(129):
    rt60 = .35 + 7.65 * (index / 128) ** 2
    rows.append([round(32768 * math.exp(-math.log(1000) * n / (11025 * rt60))) for n in DELAYS])
(P / 'father_tables.h').write_text(HDR + f"""/* g=10^(-3*delay/(11025*RT60)), RT60=.35+7.65*(index/128)^2 seconds. */
static const uint16_t mw_len[8]={arr(lens)},mw_off[8]={arr(offs)},mw_delay[8]={arr(DELAYS)};
static const uint16_t mw_ap_len[4]={arr(ALLPASS)},mw_ap_off[4]={arr(ap_offs)};
static const int16_t mw_depth[8]={arr(DEPTH)};
static const uint32_t mw_speed[8]={arr(SPEED)};
static const uint16_t mw_early[2][4]={{{arr(EARLY[0])},{arr(EARLY[1])}}};
static const int16_t mw_decay[129][8]={{
""" + ''.join(arr(r) + ',\n' for r in rows) + '};\n')
