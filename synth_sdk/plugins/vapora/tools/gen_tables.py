#!/usr/bin/env python3
"""Offline PADsynth construction; no FFT on OP-1. GPL-3.0-or-later + OP-1 permission.
WARM's two original long-loop arrays are preserved exactly. Shorter new banks
have the same 64 samples per fundamental cycle, so playback increment is shared.
"""
import hashlib,json
from pathlib import Path
import numpy as np
ROOT=Path(__file__).resolve().parents[1]

def generate():
    cfg=json.loads((ROOT/'data/voices.json').read_text())
    n,fs=cfg['master_length'],cfg['sample_rate'];ref=cfg['reference_cycles']*fs/n
    rng=np.random.Generator(np.random.PCG64(cfg['seed']))
    phase=np.exp(2j*np.pi*rng.random(n//2+1))
    endpoints=[('WARM/'+e['name'],e) for e in cfg['families'][0]['endpoints']]
    endpoints += [(e['name'],e) for e in cfg['textures']]
    allwaves=[]
    for idx,(name,e) in enumerate(endpoints):
        size=e.get('master_length',n);bins=np.arange(size//2+1);hz=bins*fs/size
        mag=np.zeros(len(bins))
        if idx<2:
            for h in range(1,81):
                f=ref*h
                if f>fs*.43:break
                amp=h**-e['rolloff'];amp*=1-e.get('odd_bias',0)*(h%2==0)
                amp*=np.exp(-(h/e.get('harmonic_cutoff',80))**2)
                sigma=(2**(e['bandwidth_cents']/1200)-1)*ref*h**e.get('bandwidth_scale',1)/2
                offsets=cfg.get('ensemble_cents',[0])
                for cents in offsets:
                    center=f*2**(cents/1200)
                    mag+=amp*np.exp(-((hz-center)/sigma)**2)/(sigma*len(offsets))
        else:
            for ratio,amp in e['partials']:
                sigma=max(fs/size*.35,(2**(e['bandwidth_cents']/1200)-1)*ref*ratio**e.get('bandwidth_scale',1)/2)
                for cents in e.get('ensemble_cents',[0]):
                    center=ref*ratio*2**(cents/1200)
                    mag+=amp*np.exp(-((hz-center)/sigma)**2)/sigma
            if 'noise' in e:
                lo,hi,slope=e['noise'];h=hz/ref
                bed=np.clip((h-lo)/.5,0,1)*np.clip((hi-h)/.5,0,1)*np.maximum(h,.25)**-slope
                # Comparable integrated energy for sparse tones and broad air.
                mag+=bed*e.get('noise_amount',.12)
        mag[0]=mag[-1]=0
        spec=mag*phase[::n//size]
        wave=np.fft.irfft(spec,size)
        spec*=cfg['rms_target']/np.sqrt(np.mean(wave**2))
        levels=[]
        for lev in range(8):
            length=size>>lev
            cut=np.clip((.40*length-bins)/(.08*length),0,1)
            window=.5-.5*np.cos(np.pi*cut)
            wave=np.fft.irfft(spec*window,size)[::size//length]
            wave-=wave.mean()
            if lev==7:wave[:]=0
            levels.append(wave)
        allwaves.append(levels)
    gains=[e.get('fixed_gain',1.) for _,e in endpoints]
    for group in {e.get('gain_group') for _,e in endpoints}-{None}:
        ids=[i for i,(_,e) in enumerate(endpoints) if e.get('gain_group')==group]
        gain=min(1.,cfg['peak_ceiling']/max(np.max(np.abs(w)) for i in ids for w in allwaves[i]))
        for i in ids:gains[i]=gain
    arrays=[];metadata=[]
    for idx,levels in enumerate(allwaves):
        for lev,wave in enumerate(levels):
            q=np.rint(wave*gains[idx]).astype('<i2');name=f'ps_t{idx}_{lev}'
            arrays.append(f'static const int16_t {name}[{len(q)}] = {{\n'+
                          '\n'.join(','.join(map(str,q[k:k+16]))+',' for k in range(0,len(q),16))+'\n};')
            metadata.append(dict(endpoint=endpoints[idx][0],level=lev,length=len(q),reference_cycles=len(levels[0])//64,
                max_bin=.4*len(q),peak=int(np.max(np.abs(q.astype(np.int32)))),dc=float(q.mean()),
                rms=float(np.sqrt(np.mean(q.astype(float)**2))),sha256=hashlib.sha256(q.tobytes()).hexdigest()))
    text='/* Generated by tools/gen_tables.py; do not edit. */\n#include <stdint.h>\n'+'\n'.join(arrays)
    text+=f'\nstatic const int16_t *const ps_tables[{len(endpoints)}][8] = {{\n'
    text+='\n'.join('{'+','.join(f'ps_t{i}_{l}' for l in range(8))+'},' for i in range(len(endpoints)))+'\n};\n'
    indices={name:i for i,(name,_) in enumerate(endpoints)}
    pairs=[tuple(indices[n] for n in c['endpoints']) for c in cfg['characters']]
    for a,b in pairs:assert len(allwaves[a][0])==len(allwaves[b][0])
    text+=f'static const uint8_t ps_family_tables[{len(pairs)}][2]={{'+','.join('{%d,%d}'%pair for pair in pairs)+'};\n'
    bits=[len(allwaves[a][0]).bit_length()-1 for a,b in pairs]
    text+=f'static const uint8_t ps_family_bits[{len(pairs)}]={{'+','.join(map(str,bits))+'};\n'
    (ROOT/'vapora_tables.h').write_text(text)
    meta=dict(numpy=np.__version__,reference_hz=ref,reference_cycles=cfg['reference_cycles'],
        loop_seconds=n/fs,common_gain=1,endpoint_gains=gains,table_bytes=sum(x['length']*2 for x in metadata),
        loop_seconds_at_c4=cfg['reference_cycles']/261.625565,
        shorter_loop_seconds_at_c4=[32/261.625565,64/261.625565,128/261.625565],
        characters=cfg['characters'],
        config_sha256=hashlib.sha256((ROOT/'data/voices.json').read_bytes()).hexdigest(),
        header_sha256=hashlib.sha256(text.encode()).hexdigest(),tables=metadata)
    (ROOT/'data/tables.json').write_text(json.dumps(meta,indent=2)+'\n')
    names=[c['name'] for c in cfg['characters']]
    (ROOT/'vapora_characters.h').write_text('/* Generated character identities; see data/voices.json. */\n#ifndef VAPORA_CHARACTERS_H\n#define VAPORA_CHARACTERS_H\nenum { PS_CHARACTERS='+str(len(names))+' };\nstatic const char *const ps_character_names[PS_CHARACTERS]={\n'+','.join(json.dumps(n) for n in names)+'\n};\n#endif\n')
    print(f'PADsynth: {len(endpoints)} endpoints, {meta["table_bytes"]} sample bytes; {meta["header_sha256"]}')
if __name__=='__main__':generate()
