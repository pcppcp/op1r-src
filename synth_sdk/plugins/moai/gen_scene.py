def rdp(p, t):
    if len(p) < 3: return p
    a, b = p[0], p[-1]; dx, dy = b[0] - a[0], b[1] - a[1]; L = math.hypot(dx, dy) or 1e-9
    d = [abs((q[0] - a[0]) * dy - (q[1] - a[1]) * dx) / L for q in p[1:-1]]
    i = max(range(len(d)), key=d.__getitem__)
    return rdp(p[:i + 2], t)[:-1] + rdp(p[i + 1:], t) if d[i] > t else [a, b]

def length(p): return sum(math.hypot(b[0] - a[0], b[1] - a[1]) for a, b in zip(p, p[1:]))

def main():
    src = open(SRC).read()
    cols, strokes = [], []
    for c, d in re.findall(r'<path stroke="#([0-9A-Fa-f]{6})" d="([^"]+)"', src):
        cols.append(c.upper())
        for m in re.finditer(r'M[^M]+', d):
            p = [tuple(map(float, q.split())) for q in re.findall(r'(-?[\d.]+ -?[\d.]+)', m.group(0))]
            if p[0] in DROP: continue
            strokes.append((len(cols) - 1, [FIT(*q) for q in rdp(p, TOL)]))
    hz = FIT(0, HORIZON)[1]
    strokes.append((cols.index('7D85F0'), [(GAP[0], hz), (GAP[1], hz)]))
    strokes.sort(key=lambda s: -999 if s[1][0] == (GAP[0], hz) else -length(s[1]))   # the horizon: always shown
    sky = [160] * 80                                              # the drawing's top per 4 px column (px)
    for _, p in strokes:
        for (xa, ya), (xb, yb) in zip(p, p[1:]):
            for x in range(max(0, int(min(xa, xb)) // 4), min(79, int(max(xa, xb)) // 4) + 1):
                sky[x] = min(sky[x], int(min(ya, yb)))
    pts, first = [], []
    for _, p in strokes:
        first.append(len(pts) // 2)
        for x, y in p: pts += [round(x * 4), round(y * 4)]
    first.append(len(pts) // 2)
    hz = round(hz)
    out = ['/* generated by gen_scene.py from scene/moai_v3c.svg - the home scene: strokes from the longest to the shortest,',
           ' * points in quarter px */',
           f'enum {{ MO_N = {len(strokes)}, MO_HZ = {hz} }};                                         /* strokes, the horizon (px) */',
           'static const uint8_t MO_RGB[%d][4] = { %s };' % (len(cols), ', '.join(
               '{ 0x%s, 0x%s, 0x%s, 0xFF }' % (c[0:2], c[2:4], c[4:6]) for c in cols)),
           f'static const int16_t MO_PTS[{len(pts)}] = {{']
    for i in range(0, len(pts), 24): out.append('    ' + ', '.join(map(str, pts[i:i + 24])) + ',')
    out.append('};')
    out.append(f'static const uint16_t MO_FIRST[MO_N + 1] = {{                                  /* each stroke\'s first point */')
    for i in range(0, len(first), 20): out.append('    ' + ', '.join(map(str, first[i:i + 20])) + ',')
    out.append('};')
    out.append('static const uint8_t MO_COL[MO_N] = {                                         /* its colour (MO_RGB) */')
    cs = [c for c, _ in strokes]
    for i in range(0, len(cs), 40): out.append('    ' + ', '.join(map(str, cs[i:i + 40])) + ',')
    out.append('};')
    out.append('static const uint8_t MO_SKY[80] = {                                           /* the drawing\'s top per 4 px (px) */')
    for i in range(0, 80, 40): out.append('    ' + ', '.join(map(str, sky[i:i + 40])) + ',')
    out.append('};')
    dp, df = [], []                                               # the digits: x, y in tenths, -1 = pen up
    for ch in '0123456789':
        df.append(len(dp) // 2)
        for n, st in enumerate(DIGITS[ch]):
            if n: dp += [-1, -1]
            for x, y in st: dp += [round(x * 10), round(y * 10)]
    df.append(len(dp) // 2)
    out.append(f'static const int16_t MO_DIG[{len(dp)}] = {{                                     /* the digits 0 .. 9: 10 x 16 in tenths, -1: pen up */')
    for i in range(0, len(dp), 24): out.append('    ' + ', '.join(map(str, dp[i:i + 24])) + ',')
    out.append('};')
    out.append('static const uint16_t MO_DIGF[11] = { ' + ', '.join(map(str, df)) + ' };')
    open(os.path.join(HERE, 'moai_scene.h'), 'w').write('\n'.join(out) + '\n')
    segs = sum(len(p) - 1 for _, p in strokes)
    print(f'{len(strokes)} strokes, {segs} lines, {len(pts) * 2 + len(first) * 2 + len(strokes) + 80} bytes, horizon {hz}')

if __name__ == '__main__':
    main()
