#!/usr/bin/env python3
"""Generate moai.svg + moai_geom.h (the geometry shared with the screen code in moai_screen.h).

The screen (320 x 160; the OP-1 shows about y < 146 of it: everything stays above), top to bottom:
  - the filter plot: log frequency 20 Hz .. 20 kHz across, dB up. Code draws the response of the ladder at the
    current cutoff / emphasis (and, while a key is held, at the moving cutoff of the latest note), plus a bar under it
    for how far the contour sweeps the cutoff;
  - left panel: the oscillator setup (number and name), then one row per oscillator: range in feet, wave, interval,
    detune and level;
  - right panel: the contour over time (a quadratic time axis, 0 .. 2.4 s, key released at 70 %): decay, sustain,
    release and depth;
  - labels, then four dials (blue cutoff / green emphasis / white contour / red decay); a ring + the page-2 label when
    a knob is on page 2 (setup / detune / osc 3).
Everything, the dials too, is drawn by code (moai_screen.h); the SVG is empty. The geometry below is the home view's.
"""
import math, os

HERE = os.path.dirname(os.path.abspath(__file__))
GREY, DARK = '#6F7173', '#3A3B3E'
PX0, PX1, PY0, PY1 = 14, 306, 4, 48           # filter plot frame
PPO = (PX1 - PX0) / 10.0                      # px per octave (20 Hz .. 20.48 kHz = 10 octaves)
Y_ZERO = 20                                   # y of 0 dB; 2 px per 3 dB (+24 .. -42 dB)
AX_Y = PY1 + 2                                # axis label row
OSC_BOX = (14, 61, 168, 104)                  # left panel x0, y0, x1, y1
ENV_BOX = (176, 61, 306, 104)                 # right panel
OSC_ROW_Y = (80, 89, 98)                      # centre lines of the three oscillator rows
DIAL_Y = 128
DIALS = [(70, '#4D9EFF'), (130, '#00ED95'), (190, '#FFFFFF'), (250, '#FF3A5D')]
LABEL_Y = 107


def fx(f):
    return PX0 + PPO * math.log2(f / 20.0)


def line(x0, y0, x1, y1, col, w=1):
    return (f'<line fill="none" stroke="{col}" stroke-width="{w}" x1="{x0:g}" y1="{y0:g}" x2="{x1:g}" y2="{y1:g}"/>')


def box(b, col=DARK):
    x0, y0, x1, y1 = b
    return [line(x0, y0, x1, y0, col), line(x1, y0, x1, y1, col), line(x1, y1, x0, y1, col), line(x0, y1, x0, y0, col)]


def svg():
    o = ['<?xml version="1.0" encoding="utf-8"?>',
         '<svg version="1.1" id="Layer_1" xmlns="http://www.w3.org/2000/svg" x="0px" y="0px"',
         '\t width="320px" height="160px" viewBox="0 0 320 160">',
         '<!-- generated by gen_svg.py - empty: everything is drawn by code (moai_screen.h) -->']
    # the dials too are drawn by code (mg_dials in moai_screen.h, at DIAL_Y / DIALS below): a parsed SVG node
    # costs R246's drawing heap about 235 bytes, and the 24 of the four dials made 5,640 of the 3,840 left
    o.append('</svg>')
    return '\n'.join(o) + '\n'


def header():
    e2 = [round(2 ** (i / 32) * 4096) for i in range(33)]            # 2^(i/32), Q12
    p2 = [round(2 ** (-i / 32) * 32768) for i in range(33)]          # 2^(-i/32), Q15
    h = ['/* generated by gen_svg.py - geometry of moai.svg */',
         f'#define MG_PX0 {PX0}', f'#define MG_PX1 {PX1}', f'#define MG_PY0 {PY0}', f'#define MG_PY1 {PY1}',
         f'#define MG_PPO_Q10 {round(PPO * 1024)}          /* px per octave, Q10 */',
         f'#define MG_YZERO {Y_ZERO}', f'#define MG_AX_Y {AX_Y}',
         f'#define MG_OSC_X0 {OSC_BOX[0]}', f'#define MG_OSC_Y0 {OSC_BOX[1]}', f'#define MG_OSC_X1 {OSC_BOX[2]}', f'#define MG_OSC_Y1 {OSC_BOX[3]}',
         f'#define MG_ENV_X0 {ENV_BOX[0]}', f'#define MG_ENV_Y0 {ENV_BOX[1]}', f'#define MG_ENV_X1 {ENV_BOX[2]}', f'#define MG_ENV_Y1 {ENV_BOX[3]}',
         f'#define MG_DIAL_Y {DIAL_Y}', f'#define MG_LABEL_Y {LABEL_Y}',
         'static const int16_t mg_row_y[3] = { ' + ', '.join(map(str, OSC_ROW_Y)) + ' };',
         'static const int16_t mg_dial_x[4] = { ' + ', '.join(str(x) for x, _ in DIALS) + ' };',
         f'#define MG_AX100 {round(fx(100))}', f'#define MG_AX1K {round(fx(1000))}', f'#define MG_AX10K {round(fx(10000))}',
         'static const uint16_t mg_exp2[33] = { ' + ', '.join(map(str, e2)) + ' };          /* 2^(i/32), Q12 */',
         'static const uint16_t mg_pow2neg[33] = { ' + ', '.join(map(str, p2)) + ' };       /* 2^(-i/32), Q15 */']
    return '\n'.join(h) + '\n'


if __name__ == '__main__':
    open(os.path.join(HERE, 'moai.svg'), 'w').write(svg())
    open(os.path.join(HERE, 'moai_geom.h'), 'w').write(header())
    print('ok')
