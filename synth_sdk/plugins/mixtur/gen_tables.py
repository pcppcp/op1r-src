#!/usr/bin/env python3
"""Generate mixtur_tables.h: divider constants and the formant knob curves (33 points, linear interpolation).

Divider n (1..24): sub-phase q = c * DIV_D[n] + (p >> 16) * DIV_R[n]  (c = wrap counter 0..n-1, p = master phase)
  DIV_D[n] = floor(2^32 / n), DIV_R[n] = floor(2^16 / n) (65535 for n = 1). Max q = 2^32 - 65536/n: never overflows.
Formant knobs (page 2, x = word / 32768; word 0 of older patches = 8192, the firmware's page-2 start value):
  F1 = 180 Hz * 2^(4.5 x)  (180 .. 4070 Hz, 392 Hz at the default)
  F2 = 500 Hz * 2^(3.5 x)  (500 .. 5660 Hz, 917 Hz at the default: a dark "o")
  Q  = 0.7 * 32^(x^0.6)    (0.7 .. 22, 3.2 at the default)
Chamberlin SVF coefficients in Q13: F = 2 sin(pi f / fs), damping q = 1 / Q. Makeup gain (Q12) keeps the loudness of the
formant pair roughly constant over Q (measured with harness analysis, see README).
"""
import math, os

FS = 88200                            # voice rate (OP1_VOICE_RATE)
N = 33
HERE = os.path.dirname(os.path.abspath(__file__))
xs = [i / (N - 1) for i in range(N)]
f1 = [180 * 2 ** (4.5 * x) for x in xs]
f2 = [500 * 2 ** (3.5 * x) for x in xs]
qq = [0.7 * 32 ** (x ** 0.6) for x in xs]
coef = lambda f: round(2 * math.sin(math.pi * f / FS) * 8192)
MAKEUP_EXP = 0.42                     # output RMS ~ Q^-0.42 for the dense undertone spectrum (measured)
LEVEL = 0.68                          # overall level (makeup at Q 0.7); peaks -3 .. -12 dBFS per voice
mk = [round(4096 * LEVEL * (q / 0.7) ** MAKEUP_EXP) for q in qq]


def arr(name, typ, v, per=11):
    rows = [', '.join(str(x) for x in v[i:i + per]) for i in range(0, len(v), per)]
    return f'static const {typ} {name}[{len(v)}] = {{\n    ' + ',\n    '.join(rows) + '\n};'


out = ['/* generated by gen_tables.py - do not edit */',
       arr('DIV_D', 'uint32_t', ['0u', '0u'] + [f'{(1 << 32) // n}u' for n in range(2, 25)], 5),
       arr('DIV_R', 'uint16_t', [0, 65535] + [65536 // n for n in range(2, 25)], 13),
       '/* formant curves over page-2 knob words (index = word >> 10, 33 points) */',
       arr('F1_COEF', 'int16_t', [coef(f) for f in f1]),
       arr('F2_COEF', 'int16_t', [coef(f) for f in f2]),
       arr('RES_Q', 'int16_t', [round(8192 / q) for q in qq]),
       arr('RES_MAKEUP', 'int16_t', mk),
       '/* for the screen: Hz and Q x 10 */',
       arr('F1_HZ', 'int16_t', [round(f) for f in f1]),
       arr('F2_HZ', 'int16_t', [round(f) for f in f2]),
       arr('RES_Q10', 'int16_t', [round(q * 10) for q in qq])]
open(os.path.join(HERE, 'mixtur_tables.h'), 'w').write('\n'.join(out) + '\n')
print('ok', [round(f) for f in f1[::8]], [round(f) for f in f2[::8]], [round(q, 2) for q in qq[::8]], mk[::8])
