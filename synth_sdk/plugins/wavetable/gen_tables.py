"""Writes wavetables.h for the wavetable engine: 8 single-cycle waves of 256 int16 samples (additive, at most 32
harmonics so the table itself does not alias) and the cutoff table (Q15 one-pole coefficients for 30 Hz - 16 kHz at 88.2 kHz), and
wavetable_pairs.h for the Blackfin kernel (wavetable_dsp.S): the same waves as one word per point, the step to the
next point in the high half and the point in the low half, so one load feeds one interpolation."""
import math, os

N, H = 256, 32
FS = 88200.0                  # R246 renders a voice at 88.2 kHz (OP1_VOICE_RATE): the ladder's one-poles run at that rate
def additive(amp):            # amp(k) for harmonic k = 1..H
    w = [sum(amp(k) * math.sin(2 * math.pi * k * i / N) for k in range(1, H + 1)) for i in range(N)]
    m = max(abs(x) for x in w)
    return [round(x / m * 30000) for x in w]

def formant(k):               # vocal "ah": peaks near harmonics 4 and 7 of a low note
    return math.exp(-((k - 4) / 1.6) ** 2) + 0.6 * math.exp(-((k - 7) / 1.8) ** 2) + 0.15 / k

waves = [
    ("sine", lambda k: 1.0 if k == 1 else 0.0),
    ("warm", lambda k: {1: 1.0, 2: 0.45, 3: 0.2, 4: 0.08}.get(k, 0.0)),
    ("triangle", lambda k: ((-1) ** ((k - 1) // 2)) / k ** 2 if k % 2 else 0.0),
    ("saw", lambda k: 1.0 / k),
    ("square", lambda k: 1.0 / k if k % 2 else 0.0),
    ("pulse", lambda k: math.sin(math.pi * k * 0.25) / k),
    ("vocal", formant),
    ("digital", lambda k: 1.0 / k if k in (1, 3, 8, 13, 21, 29) else 0.0),
]

def cutoff(i, n=64):          # g = 1 - exp(-2 pi fc / fs), fc exponential over the knob
    fc = 30.0 * (16000.0 / 30.0) ** (i / (n - 1))
    return round((1 - math.exp(-2 * math.pi * fc / FS)) * 32767)

HEADER = "/* Copyright (C) 2026 Hundekraft. GPL-3.0-or-later with the OP-1 firmware permission (see LICENSE and NOTICE). */"
out = [HEADER, "/* generated by gen_tables.py */", "#include <stdint.h>", f"#define WT_WAVES {len(waves)}", f"#define WT_SIZE {N}",
       "static const int16_t wt_waves[WT_WAVES][WT_SIZE + 1] = {"]
pairs = [HEADER, "/* generated by gen_tables.py: wt_waves[w][i + 1] - wt_waves[w][i] << 16 | (uint16_t)wt_waves[w][i] */",
         "#include <stdint.h>", "static const uint32_t wt_pairs[WT_WAVES][WT_SIZE] = {"]
for name, f in waves:
    w = additive(f)
    t = w + [w[0]]
    assert all(abs(t[i + 1] - t[i]) < 32768 for i in range(N))    # the step fits the kernel's 16-bit multiply
    pairs.append(f"    /* {name} */ {{" + ", ".join("0x%08x" % (((t[i + 1] - t[i]) & 0xFFFF) << 16 | (t[i] & 0xFFFF)) for i in range(N)) + "},")
    out.append(f"    /* {name} */ {{" + ", ".join(map(str, w + [w[0]])) + "},")
out += ["};", "#define WT_CUTOFFS 64", "static const int16_t wt_cutoff[WT_CUTOFFS + 1] = {",
        "    " + ", ".join(str(cutoff(i)) for i in range(64)) + f", {cutoff(63)}", "};"]
here = os.path.dirname(os.path.abspath(__file__))
open(os.path.join(here, "wavetables.h"), "w").write("\n".join(out) + "\n")
open(os.path.join(here, "wavetable_pairs.h"), "w").write("\n".join(pairs + ["};"]) + "\n")
