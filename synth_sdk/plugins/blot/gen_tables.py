#!/usr/bin/env python3
"""blot_tables.h: the coupled ladder's coefficients per 1/8 octave, the resonance curve and the decay time per knob step.
    python3 gen_tables.py > blot_tables.h
The ladder is the TB-303 filter of Open303 (Robin Schmidt, MIT, rosic_TeeBeeFilter): b0 and k as polynomial / rational
fits of the cutoff, see blot.c."""
import math

SR = 44100
F0 = 30.0                       # cutoff at octave 0
N = 73                          # 0 .. 9 octaves in 1/8 steps (15.4 kHz), the cutoff holds there


def poly(fc):
    fx = fc * 0.7071067811865476 / SR
    b0 = (0.00045522346 + 6.1922189 * fx) / (1.0 + 12.358354 * fx + 4.4156345 * fx * fx)
    k = fx*(fx*(fx*(fx*(fx*(fx+7198.6997)-5837.7917)-476.47308)+614.95611)+213.87126)+16.998792
    return b0, k


rows = [poly(F0 * 2 ** (i / 8)) for i in range(N)]
tau = [round(40 * 2 ** (4 * i / 16)) for i in range(17)]     # decay time constant 40 .. 640 ms
rsk = [(1 - math.exp(-3 * i / 16)) / (1 - math.exp(-3)) for i in range(17)]   # resonance knob -> r (Open303's curve)

print('/* generated by gen_tables.py: do not edit */')
print(f'#define AC_G_N {N}')
print('static const uint16_t ac_b0[AC_G_N] = {   /* stage coefficient b0, Q16, at %g Hz * 2^(i / 8) */' % F0)
for i in range(0, N, 9):
    print('    ' + ', '.join('%5d' % round(r[0] * 65536) for r in rows[i:i + 9]) + ',')
print('};')
print('static const uint16_t ac_kp[AC_G_N] = {   /* k polynomial (feedback at resonance 1, g = kp / 17), Q8 */')
for i in range(0, N, 9):
    print('    ' + ', '.join('%5d' % round(r[1] * 256) for r in rows[i:i + 9]) + ',')
print('};')
print('static const int16_t ac_rsk[17] = { ' + ', '.join(str(round(v * 32767)) for v in rsk) + ' };   /* resonance knob / 2048 -> r, Q15 */')
print('static const int16_t ac_tau_ms[17] = { ' + ', '.join(map(str, tau)) + ' };   /* decay knob / 2048 */')
