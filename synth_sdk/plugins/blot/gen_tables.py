#!/usr/bin/env python3
"""blot_tables.h: ladder stage coefficient per 1/8 octave, and the decay time per knob step.
    python3 gen_tables.py > blot_tables.h"""
import math

SR = 44100
F0 = 30.0                       # cutoff at octave 0
N = 81                          # 0 .. 10 octaves in 1/8 steps
G_MAX = 0.85                    # stage coefficient cap (stable with full feedback)

g = [min(G_MAX, 1 - math.exp(-2 * math.pi * F0 * 2 ** (i / 8) / SR)) for i in range(N)]
tau = [round(40 * 2 ** (4 * i / 16)) for i in range(17)]     # decay time constant 40 .. 640 ms

print('/* generated by gen_tables.py: do not edit */')
print(f'#define AC_G_N {N}')
print('static const int16_t ac_g[AC_G_N] = {   /* Q14 one-pole coefficient, %g Hz * 2^(i / 8) */' % F0)
for i in range(0, N, 9):
    print('    ' + ', '.join('%5d' % round(v * 16384) for v in g[i:i + 9]) + ',')
print('};')
print('static const int16_t ac_tau_ms[17] = { ' + ', '.join(map(str, tau)) + ' };   /* decay knob / 2048 */')
