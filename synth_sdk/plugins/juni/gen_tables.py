#!/usr/bin/env python3
"""Generate juni_tables.h: the fixed-point tables of the JUNI engine (juni.c).

    python3 gen_tables.py        (writes juni_tables.h next to this file)

CUT_G   cutoff (MIDI note) -> one-pole coefficient g, Q15, at the internal 22.05 kHz rate
KSELF   cutoff -> the ladder feedback k (Q12) where it starts to self-oscillate. The ladder feeds back one sample
        late, so this k moves with g; RESONANCE is scaled by it, and its top is "just singing" at every cutoff.
LOG2    12 * log2(1 + i / 64) semitones, Q8: the note of a phase step, for key tracking
"""
import cmath, math, os

FS = 22050.0
CUT_MAX = 120                    # MIDI 120 = 8.4 kHz, below the internal Nyquist


def g_of(n):
    f = 440.0 * 2 ** ((n - 69) / 12.0)
    return 1.0 - math.exp(-2 * math.pi * f / FS)


def kself(g):
    """the least k where k * z^-1 * (g / (1 - (1 - g) z^-1))^4 reaches -1 on the unit circle"""
    def pole(w):                                        # one stage's response
        z1 = cmath.exp(-1j * w)
        return g / (1 - (1 - g) * z1)

    def lag(w):                                         # the loop's phase lag, unwrapped (grows with w)
        return w - 4 * cmath.phase(pole(w))

    lo, hi = 0.0, math.pi                               # bisect for a lag of pi
    for _ in range(80):
        mid = (lo + hi) / 2
        lo, hi = (mid, hi) if lag(mid) < math.pi else (lo, mid)
    return 1 / abs(pole(lo)) ** 4


def rows(vals, per=12):
    return ',\n'.join('    ' + ', '.join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))


def main():
    cut_g = [min(32767, round(g_of(n) * 32768)) for n in range(CUT_MAX + 1)]
    ks = [round(kself(g_of(n)) * 4096) for n in range(CUT_MAX + 1)]
    log2 = [round(256 * 12 * math.log2(1 + i / 64)) for i in range(65)]
    inc440 = 440.0 * 2 ** 32 / 44100.0                 # the OP-1's phase step (44.1 kHz) of A4
    off = round(256 * (69 - 12 * math.log2(inc440)))   # inc = (m / 2^15) * 2^L, m in [2^15, 2^16)
    out = f'''/* Generated by gen_tables.py: do not edit. JUNI's fixed-point tables (see gen_tables.py). */
#define CUT_MAX {CUT_MAX}
static const uint16_t CUT_G[{len(cut_g)}] = {{
{rows(cut_g)}
}};
static const uint16_t KSELF[{len(ks)}] = {{
{rows(ks)}
}};
static const uint16_t LOG2_Q8[65] = {{
{rows(log2)}
}};
#define NOTE_OFF_Q8 ({off})          /* note (Q8) = 12 * 256 * L + LOG2_Q8[...] + NOTE_OFF_Q8, L = bit length - 1 */
'''
    with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'juni_tables.h'), 'w') as f:
        f.write(out)
    print('KSELF at notes 24/60/96/120:', [ks[n] / 4096 for n in (24, 60, 96, 120)])


if __name__ == '__main__':
    main()
